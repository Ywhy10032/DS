/**
  ******************************************************************************
  * 任务调度
  *
  *   KEY1  短按  切换任务(仅在未运行时有效，避免跑着跑着被误切)。
  *               只在任务一~任务六之间循环，隐藏的任务七不参与
  *   KEY1  长按  直接启动隐藏的任务七(倒车)，见下面任务七参数区
  *   KEY2  开始当前任务；运行中再按一次立即停止并刹车
  *
  * 任务二：小车置于 A 点，按键启动后沿黑线顺时针行驶一圈并停到 A 点，
  *         计时停止并显示行驶总时间。要求 ≤20s、停车偏差 ≤2cm。
  *         A 点有一道横着的黑胶带，用它作为终点判据。
  ******************************************************************************
  */

/* ================= 车体参数 ================= */

/* 轮子直径(mm)，实测值。用于把编码器计数换算成行驶距离 */
#define TASK_WHEEL_DIAMETER_MM      67.0f

/**
  * ---------------- 加速度的建立时间(秒) —— 载球任务共用 ----------------
  *
  * 速度斜坡(Task_RampBase)保证了速度不突变，但【加速度本身还是突变的】：
  * 起步那一拍 applied 从 0 一跳就是整个 TASKxx_ACCEL_RPM_PER_S，斜坡走完
  * 又一跳回 0。球感受到的是加速度，所以这两跳各是一次冲击；而加速度前馈
  * 跟着 applied 走，杆的倾角也跟着在一个 20ms 拍里甩出去 —— 那一甩本身
  * 又是一次甩球(和任务三启动时目标阶跃甩杆是同一个机理)。
  *
  * 加这道限制之后，加速度自己也走一段斜坡(即限制 jerk)：在这个时间内从 0
  * 建立到满值，收尾时同样提前收回 0，速度曲线变成 S 形。杆的角速度降到
  * 原来的十几分之一。
  *
  * 用【时间】而不是直接写死一个 jerk 值：加速段和减速段的幅值可以差好几倍
  * (任务四就是 40 对 120)，写死 jerk 的话幅值大的那一边建立时间会跟着长
  * 好几倍；用时间表示则两边一样长，也更好估时间代价 —— 每次加速度换挡
  * 大约多花 这个时间的一半。
  *
  * 0.25s：起停各两次换挡，一趟合计约 0.25s 的代价，任务四/五的预算都扛得住。
  * 起步还是被拽 -> 可以往 0.4 加(更柔和)；觉得起步太肉 -> 往 0.15 减。
  */
#define TASK_ACCEL_RISE_S           0.25f

/* ================= 任务一参数 ================= */

/**
  * 任务一：舵机在机构安全行程内往复摆动 —— 停在 1050us 一秒、匀速升到 2400us、
  *         停一秒、再匀速降回来，如此循环，按 KEY2 停止并把杆放回水平点。
  *
  * 车全程不动(见 Task_UsesVehicle())。行程端点、扫描速度、两端停留时间都在
  * servo.h 里(SERVO_SAFE_MIN_US / SERVO_SAFE_MAX_US / SERVO_DEMO_*)，
  * 这里不再另设参数 —— 端点必须和限幅用的是同一对数，写两份迟早会对不上。
  *
  * 运行期间球杆闭环被临时关掉：两者都在每拍写舵机脉宽，同时开就是互相覆盖。
  * 停止时按进入前的状态原样还回去。
  */

/* ================= 任务二参数 ================= */

/**
  * 一圈的长度(m)。
  *
  * !! 这里要填的是【里程读数意义上】的一圈，不是拿卷尺量赛道的值 !!
  * 下面三个派生量(终点窗口 / 蠕行起点 / 里程兜底)全部拿它和 s_distance_m
  * 比大小，只要和轮径标定自洽就行，绝对值准不准无所谓。
  *
  * 6.00 来自实测：三次跑车里两次由横线正常判到终点，屏幕上定格的 D 分别是
  * 5.96 和 6.03(第三次没判到，走了里程兜底停在 6.44)。也就是说车跑到 A 点
  * 时里程读数就是 6.0，而不是原先填的 6.14 —— 差的这 14cm 会让蠕行起点和
  * 终点窗口整体后移 14cm，蠕行段被吃掉近一半。
  */
#define TASK_LAP_LENGTH_M          6.00f

/* ---------------- 终点窗口(任务二 / 五 / 六 共用) ----------------

   跑到"一圈长度减这个余量"才开始找终点横线。它有两个作用：

   1. 起跑时车就压在 A 点横线上，不设下限的话按下启动的瞬间就判"跑完一圈"。
   2. 【更重要】窗口一开，剩下唯一可能出现横线的地方就只有 A 点了，于是判据
      可以在窗口内大胆放宽(见下面两条)，而不必担心弯道误判 —— 原来判据必须
      同时满足"4 路黑 + 偏差 ≤20mm"这种零余量的严条件，正是因为它全程生效，
      得防着赛道中段的斜穿误判。窗口 + 松判据，比全程一套严判据可靠得多。

   余量【不能给大】：实测两次正常判到 A 点时里程是 5.96 / 6.03，重复性约
   ±5cm，0.35m 已经是 7 倍余量。而给到 0.60m 时窗口开在 5.40 —— 那里车还在
   弯道里，实测就是窗口一开的【那一拍】立刻误判停车(屏幕定格 D:5.40，正好
   等于开窗位置)。0.35 与蠕行起点重合，含义也统一：进窗口 = 开始减速找终点。 */
#define TASK_FINISH_WINDOW_M        (TASK_LAP_LENGTH_M - 0.35f)

/* 窗口内的横线判据(默认值见 tracking.h 的 TRACK_CROSS_*)。

   路数门槛【维持 4，不要再降】。曾经降到 3，结果是车在弯里就停 —— 实测
   弯道能稳定凑出 3 路黑：18mm 宽的纵线在车带横摆角时，落在阵列上的截距是
   18/cos(横摆角)，四五十度就有 25mm，正好盖住 3 个探头(实测两组弯道数据
   都是 3 路、总黑度 608 / 626)。所以"3 路"根本不是横线的特征。
   真横线实测两次都是 4 路、总黑度 ~800，4 这个门槛是够用的；而真正给
   "路数掉档"兜底的是 tracking.c 里的总黑度判据和跨中线判据，不是降门槛。

   偏差门槛 20 -> 35mm：出弯口还没完全回正，转向环为了跟住弯本来就带着
   十几毫米的稳态偏差。实测两次成功判到横线时 OFF 分别是 -13.0 和 -9.0
   (车稳定地偏在线右侧十几毫米)，20mm 的门槛只剩 7mm 余量 —— 也就是说
   【路数够了也会被这一条卡掉】，这多半才是"到 A 点停不下来"的直接原因。

   顺带解释为什么压在横线上 OFF 反而不是 0：横线只有 50mm 宽，盖住的是
   -30/-18/-6/+6 这 4 路(实测)，这一簇本身就不对称，质心自然落在 -12 附近。
   横向再偏 12mm 就变成 -42~-6，质心 -24，直接顶穿原来的 20mm 门槛。
   放宽到 35 是安全的：挡弯道误判的活儿已经交给"跨中线"那一票否决了。 */
#define TASK_CROSS_MIN_CH           4
#define TASK_CROSS_MAX_OFFSET_MM    35.0f

/* ---------------- 现场不对劲时往哪边动 ----------------
   A 点在出弯与直线的交汇处，也就是说窗口开头那 0.6m 很可能还在弯里，
   放宽后的判据在弯里【有可能】被斜穿的纵线蒙对。两种症状，两个方向：

   -冲过 A 没停(或者靠里程兜底才停)：判据还是太严。
    先看屏幕 DK(任务停下来后显示的是过 A 那几拍的峰值)：
      峰值 = 3   -> 判据里被偏差门槛卡住了，加大 TASK_CROSS_MAX_OFFSET_MM
      峰值 ≤ 2   -> 是路数本身不够，降 tracking.h 的 TRACK_CROSS_WEIGHT_TH，
                    或者启用总黑度判据(调低 TRACK_CROSS_SUM_TH)
   -停在 A 【之前】(停在弯里)：判据太松。先看屏幕定格的 D：
      D ≈ 开窗位置(TASK_FINISH_WINDOW_M) -> 是窗口开在弯里了，缩小上面的
                                            0.35，别动判据
      D 明显在窗口中间           -> 才是判据本身太松，按
                                    TRACK_CROSS_SUM_TH 调高 -> 收紧
                                    TASK_CROSS_MAX_OFFSET_MM 的顺序动 */

/* ---------------- 终点减速(可选) ----------------
   150rpm 约 0.5m/s，光靠"看到横线再刹车"很难压进 2cm：
   外环 20ms 的检测延迟本身就是 10mm，再加上刹车距离必然超标。
   跑到"一圈长度减 0.4m"时降到蠕行速度，这样看到横线几乎能立刻停住。

   !! 这个功能完全依赖里程的准确性，而里程又依赖上面的 TASK_WHEEL_DIAMETER_MM !!
   轮子直径填错会导致减速点跑偏：填大了会提前减速(只是慢一点，无害)，
   填小了会来不及减速甚至冲过终点。务必先量准轮径再依赖它。

   蠕行区必须留够"减速"和"真正匀速爬行"两段。装上摆杆机构后车变重、减速度
   下降，光是从 150rpm 降到蠕行速度就要十几厘米 —— 区间给小了的话，车到 A
   点时还在减速途中，是带着速度撞线的，2cm 根本守不住。
   0.40m 的代价约 2s，而整圈只要 13.8s，离 20s 的上限还很宽裕。 */
#define TASK2_CREEP_ENABLE          1
#define TASK2_CREEP_START_M         (TASK_LAP_LENGTH_M - 0.35f)
#define TASK2_CREEP_RPM             40.0f

/* ---------------- 里程兜底停车 ----------------
   万一横线没被识别到(标记太窄、被磨损、车压偏)，光靠视觉判据车会一直跑下去。
   跑过一圈长度再加这点余量还没看到横线，就按里程直接停 —— 停在 A 点附近，
   总比冲第二圈强。里程有轮滑误差，所以只作兜底，正常应该由横线先触发。

   余量给 0.30m：给太小的话，一旦里程读多了一点(车变重后轮子打滑增多，
   里程往往偏大)，兜底会抢在横线之前触发，车反而停在 A 点【之前】。
   兜底的职责是防止跑第二圈，不该参与正常的停车判定。 */
#define TASK2_DIST_STOP_ENABLE      1
#define TASK2_DIST_STOP_M           (TASK_LAP_LENGTH_M + 0.30f)

/* ================= 任务三参数 ================= */

/**
  * 任务三：小车【静止】，摆杆控制装置把钢球从中心 O 送到 +5cm 处，
  *         到达后折返，再送到 -5cm 处并稳定在该点附近。
  *         运行时间 ≤5s，±5cm 处的最大误差绝对值 ≤1cm。
  *
  * 全程车不动，只有摆杆工作 —— 见 Task_UsesVehicle()。
  *
  * ---------------- 全程闭环 + 刹车曲线提前减速 ----------------
  *
  * 状态机只有三段，非常简单(见 task.c 的 Task3_Run)：
  *   GO_PLUS   目标 = +5cm，够到容差就换目标
  *   GO_MINUS  目标 = -5cm，够到容差就进入 SETTLE
  *   SETTLE    连续待在容差内 TASK3_SETTLE_MS 就判定完成、计时定格，
  *             但【闭环不关】—— 规则要求"稳定在该点附近"，松手就散不算稳定
  *
  * 减速这件事【不在状态机里】，由 ball.c 位置环的刹车限速统一负责：
  *
  *     v_cap = sqrt(2 x a x 剩余距离)        a = TASK3_BRAKE_ACCEL_CMS2
  *
  * 含义是"以恒定减速度 a 刹车、正好在目标处降到 0"所允许的最大速度。球在
  * 任何时刻的速度都对应着"剩下的距离刚好够刹住"，所以物理上不存在"冲到
  * 目标附近才发现刹不住"。详见 ball.h 的 BALL_POS_BRAKE_CMS2。
  *
  * ---------------- 为什么是这个方案(踩坑记录，别再走回头路) ----------------
  *
  * 【纯 P + Kd 压过冲：死路】最早就是这么干的，过冲压不住，于是把位置环
  * Kd 从 0.022 一路加到 0.08/0.12/0.15/0.3 —— 结果是振荡越来越厉害。原因：
  * Kd 作用在【视觉测出来的速度】上，那个信号带着 60fps 采样 + 低通滤波的
  * 滞后，Kd 越大等于让这段滞后在环路里占的权重越重。这条路不要再试。
  *
  * 【等速度阈值再折返：死路】曾用"位置够近 + |速度| ≤ 阈值"决定何时从 +5
  * 折返，阈值在 3.0/6.0 之间来回调都不理想。根子是：逼近 +5cm 那段本身是
  * 欠阻尼振荡，球速度最低的地方恰恰是它荡到最远的地方，"等速度够慢"等于
  * 在等它荡到头，阈值越紧越是拖到更晚的极值才触发。
  *
  * 【开环定时定角度：能跑但脆】三段定时摆舵机确实能把球送到位，但每一段
  * 时长都要针对当前的摩擦/电量/桌面标定，换个场地就得重标；而且最后的定点
  * 完全靠标定的静态平衡角，那个角本身会随灰尘、电量慢慢漂。
  *
  * 【现在这版】把"提前减速"这件事从"猜时长"变成"按物理算"：减速起点不再
  * 由增益或秒表偶然决定，而是由"还剩多少距离、能刹多快"直接算出来。闭环
  * 全程在环，位置有偏差随时能纠，也不怕摩擦/电量漂移。
  *
  * ---------------- 时间预算 ----------------
  * 规则要求 ≤5s 跑完 5cm + 10cm。峰值速度由 TASK3_VEL_LIMIT_CMS 和刹车
  * 曲线里较小的那个决定：a 越小曲线越保守、越早减速、越慢但越稳。如果实测
  * 时间超了，优先加大 a(而不是加大 vel_limit) —— 加大 a 是"敢晚点刹车"，
  * 加大 vel_limit 只是提高巡航上限，而这一趟大部分时间受刹车曲线约束，
  * 提高上限往往没用。
  */

/* 摆杆中心 O 的实测位置，以及 ±5cm 两个目标点 —— 这三个就是闭环的目标值 */
#define TASK3_CENTER_CM         12.5f
#define TASK3_PLUS_CM           (TASK3_CENTER_CM + 5.0f)   /* 17.5 */
#define TASK3_MINUS_CM          (TASK3_CENTER_CM - 5.0f)   /*  7.5 */

/**
  * ---------------- 刹车曲线的减速度(cm/s²) —— 提前减速的核心参数 ----------------
  *
  *     速度上限 = sqrt(2 x a x 剩余距离)
  *
  * 装进 Ball_Tune.pos_brake_cms2，由 ball.c 的位置环每拍施加，见那边和
  * ball.h 的 BALL_POS_BRAKE_CMS2。全局默认是 0(关闭)，只有任务三打开 ——
  * 任务四/五/六是"球稳在中心"的小幅修正，误差小到根本顶不到这条曲线。
  *
  * 物理含义直接给出了调参方向，不用猜：
  *   -调【小】 -> 曲线更保守，更早开始减速，更稳但更慢
  *   -调【大】 -> 更晚才减速，更快但逼近实际刹车能力，过头就会冲过目标
  *
  * 上限由机构决定：闭环能给的最大减速度受舵机输出限幅 BALL_OUTPUT_LIMIT_US
  * (=560us)约束，按开环标定时的数据反推大致 25~30cm/s²。a 设得比这个还大，
  * 曲线要求的减速度就超出了机构能力，必然刹不住。所以 a 的安全区间大致是
  * 10~20，取值越靠近 30 越危险。
  *
  * 10.5 是实测下来的值 —— 早期用固定交接窗口时试过 15，冲过头，降到 10 才
  * 干净。留着这个偏保守的值：任务三时间预算(5s 跑 15cm)相当宽裕，没必要
  * 为了抢那几百毫秒冒冲出容差的风险。真要提速也是先动这里，而不是动
  * TASK3_VEL_LIMIT_CMS(见下面那条的说明)。
  */
#define TASK3_BRAKE_ACCEL_CMS2  3.0f

/**
  * 速度指令上限(cm/s)。
  *
  * 注意这一趟【大部分时间受刹车曲线约束，而不是受这个上限约束】：a=10.5 时
  * sqrt(2 x 10.5 x d)，距离 5cm 处算出 10.2cm/s、10cm 处 14.5cm/s，
  * 也就是说只有折返那段刚起步的一小会儿才可能顶到 12。所以调大这个数对
  * 总耗时几乎没影响，想提速要去调 TASK3_BRAKE_ACCEL_CMS2。
  *
  * 它真正的作用是【兜住起步冲刺】：刚换目标那一瞬间剩余距离最大，刹车曲线
  * 算出来的允许速度也最大，没有这道上限的话内环会一口气把球推到很快。
  */
#define TASK3_VEL_LIMIT_CMS     12.0f

/* 判定"已到达 ±5cm"的容差(cm)。指标是 ≤1cm，取 0.6 留 0.4cm 余量给视觉
   误差。GO_PLUS 用它决定何时折返，GO_MINUS/SETTLE 用它判定到位与稳定 */
#define TASK3_ARRIVE_CM         0.6f

/* 到 -5cm 后要连续保持在容差内这么久，才判定"稳定在该点附近"、停表。
   别砍太短——这段时间过后任务判定"完成"，砍太短有被裁判在还没焊死的时候
   看到的真实风险。停表之后闭环【不关】，会一直按着球 */
#define TASK3_SETTLE_MS         350

/**
  ******************************************************************************
  * ---------------- 任务三专用的球杆增益 ----------------
  *
  * Task_Start() 装载(见 task.c)，跑完整个任务三都用这一组。
  *
  * 为什么要单独一组而不是直接用 ball.h 的全局默认值：
  *   1. 全局那组是给任务四/五/六【小车行驶中稳球】调的，工况完全不同
  *      (那边要兼顾车的加减速扰动，这边是静止状态下的点到点)，共用一组
  *      等于互相绑架 —— 为这边调好的值可能让那几个任务变差。
  *   2. Task_Start() 开头会调 Ball_ResetTune() 把参数冲回默认，所以用 vofa
  *      的 O/P 指令在【运行前】调的值，一按 KEY2 就没了。装成任务专属的
  *      一组，每次启动都会重新加载，行为可复现。
  *
  * ---------------- 现场调参的正确姿势 ----------------
  * 因为上面第 2 条，调参要在【任务跑起来之后】发 O/P 指令。最方便的是等
  * 一趟跑完(计时已定格、闭环还在按着球)再发，改增益立刻生效、也不会再被
  * 重置；下一次按 KEY2 会重新加载宏里的值，所以调满意之后记得誊抄回来。
  *
  *   O<kp>,<ki>,<kd>   改位置环(外环)
  *   P<kp>,<ki>,<kd>   改速度环(内环)
  *
  * ---------------- 晃动了先动哪个 ----------------
  * 晃动几乎都出在【外环】，内环那组(33/70/0)是按 ball.h 的整定步骤实测
  * 收敛过的"推哪停哪"，先别动。
  *
  *   -大幅、慢周期的来回荡(欠阻尼阶跃响应那种衰减振荡) -> 降 TASK3_POS_KP
  *   -小幅、快速的抖        -> 降 TASK3_POS_KD(微分在放大视觉噪声)
  *   -"稳一会儿、猛地窜一下、又稳住"周而复始 -> 是积分顶静摩擦的极限环，
  *    降 TASK3_POS_KI(下面已经先设成 0，理由见那条注释)
  ******************************************************************************
  */

/**
  * 外环 Kp。
  *
  * 1.6 -> 1.25：1.6(全局默认)实测在到位后有明显的衰减振荡，降 Kp 是压这种
  * 振荡的首选手段 —— 阻尼比大致正比于 Kd/sqrt(Kp)，降 Kp 能提高阻尼比，
  * 而且不像加 Kd 那样会放大测速信号的滞后(见下面 KD 那条的教训)。
  *
  * 现在有了刹车曲线兜着大位移段的减速，Kp 的职责只剩"最后一两厘米的收敛"，
  * 可以给得比过去保守 —— 降它主要影响收敛速度，不影响能不能跑完全程。
  */
#define TASK3_POS_KP            1.25f

/**
  * 外环 Ki，【故意设成 0】，和全局默认(BALL_POS_KI=0.2)不一样。
  *
  * 那个 0.2 是为了解决"切到任务三等球归位时，误差卡在 0.3cm 不再收敛"
  * 加的 —— 那是【等待居中】阶段的毛病(用的是全局默认参数)，和任务跑起来
  * 之后是两回事。
  *
  * 位置环的积分在【定点保持】这个工况下反而是晃动的元凶：球停住之后误差
  * 很小，积分持续往一个方向充电，充到刚好越过静摩擦门槛的瞬间把球猛地
  * 推动一下，冲过头，反向修正，重新稳住，然后又开始充电 —— 表现为"稳一
  * 会儿、抖一下、又稳住"周而复始。这就是 ball.h 里 BALL_VEL_I_DEADBAND_CMS
  * 那段注释描述的经典极限环，只不过那边发生在内环、用积分死区解决了，
  * 而位置环【没有】死区保护。
  *
  * 也本来不需要外环积分：顶住摩擦/管子下垂所需的那份常驻倾角，是速度环
  * 积分的职责(BALL_VEL_KI=70)，它已经在干这件事了；外环再来一份纯属重复
  * 且互相打架。
  *
  * 如果实测发现稳态总差几毫米收不掉，再从 0.05 这种很小的值往上加，
  * 别直接用 0.2。
  */
#define TASK3_POS_KI            0.0f

/**
  * 外环 Kd。
  *
  * !! 别往大了调 !! 这条路在任务三上踩过很深的坑：早期为了压大位移的过冲，
  * 把它从 0.022 一路加到 0.08/0.12/0.15/0.3，结果是振荡越来越厉害 ——
  * 微分作用在【视觉测出来的速度】上，那个信号本身有 60fps 采样 + 低通滤波
  * 带来的滞后，Kd 越大等于让这段滞后在环路里占的权重越重。
  *
  * 现在压过冲的活儿由刹车曲线(TASK3_BRAKE_ACCEL_CMS2)干了，Kd 更没有往上
  * 加的理由。看到小幅高频的抖，往【小】调。
  */
#define TASK3_POS_KD            0.022f

/* 内环三个增益。沿用 ball.h 里按整定步骤实测收敛过的那组(推一下最多回摆
   一次、长时间观察不发作)，没有理由改动它 —— 晃动先从外环找 */
#define TASK3_VEL_KP            33.0f
#define TASK3_VEL_KI            70.0f
#define TASK3_VEL_KD            0.0f

/* 时间兜底(ms)。正常 3s 上下跑完，超时说明这一趟已经失败，只为防止一直
   跑下去。注意它触发时【不关闭球杆闭环】，球还是被按着的 */
#define TASK3_RUN_TIME_MS       15000

/* ================= 任务四参数 ================= */

/**
  * 任务四：小车置于 A 点、钢球置于摆杆中心 O，启动后顺时针巡线通过 B 位置。
  *         AB 间行驶时间 ≤8s，行驶中钢球须稳定在摆杆中心附近，误差 ≤1cm。
  *         AB 段全是直线，但 B 之后紧接着就是弯道。
  */

/* 实测 A->B 的距离 */
#define TASK4_B_DISTANCE_M          1.6f

/* 基准速度。含起步斜坡的总时间 T = 距离/v + 0.5 x 斜坡时间。
   75rpm 时 T = 1.6/0.263 + 0.31 = 6.4s，90rpm 时 T = 1.6/0.316 + 0.38 = 5.4s，
   正好快 1s。注意这是个比值关系，即便实测的绝对值和模型有出入，
   75->90 省下的仍然是约 1 秒。 */
#define TASK4_BASE_RPM              90.0f

/* 停车点：过 B 之后再走这么远就开始减速。
   B 之后就是弯道，而任务四用的是软转向 + 关掉弯道减速，这套参数过不了弯，
   所以必须在刚通过 B 时就停住，不能让车开进弯道。 */
/* 0.5 -> 0.25：这一改是【为了让车停在原来那个位置】，不是想少跑一段。
   减速斜坡从 120 放缓到 40 之后，刹停本身要走的距离从约 0.16m 变成约 0.40m
   (90rpm = 0.316m/s，2.5s 停住，平均半速)。减速起点不往回挪的话，车会一路
   滑到 B+0.9m —— 而 B 之后紧接着就是弯道，这套软转向参数过不了弯。
       原来： B+0.50 起减速，+0.16 滑行 -> 停在 B+0.66
       现在： B+0.25 起减速，+0.40 滑行 -> 停在 B+0.65
   过 B 之后仍有 0.25m(约 0.8s)的匀速段，减速动作照样落在评分时刻【之后】,
   这一点和任务五的 TASK56_COAST_MS 是同一个用意。 */
#define TASK4_STOP_DIST_M           (TASK4_B_DISTANCE_M + 0.25f)

/* 起步加速斜坡(rpm/s)。
   球的稳定性取决于【加速度】而不是速度：从 0 瞬间跳到 90rpm，这一下冲击
   全砸在球上，起步就会把球甩到摆杆一端，后面再稳也来不及。
   前馈(BALL_FF_US_PER_RPMS)能抵消掉大部分惯性影响，但摆杆的倾角权限有限，
   加速度太大时前馈会被限幅削掉，球照样被拽走。所以两手都要抓：
   前馈负责"提前倾杆"，这个值负责"别一上来就要求太大的倾角"。
   60rpm/s 意味着 1.5s 匀加速到位，比 120 多花约 0.4s，8s 的预算扛得住。

   60 -> 40：这一改是【跟着 ball.h 的 BALL_FF_US_PER_RPMS 2.0->7.0 一起做的】，
   不是任务四自己测出来的。前馈增益改准之后，60rpm/s 要求的常驻倾角是
   60x7=420us，占掉 560us 权限的 75%，速度环积分顶摩擦就没空间了 —— 前馈
   一饱和，"提前倾杆"这件事就等于没做。40rpm/s 需要 280us，留一半给反馈。
   时间代价：0->90rpm 从 1.5s 变成 2.25s，A->B 约多花 0.4s(6.4 -> 6.8s)。
   !! 8s 的余量被吃掉一截，改完务必重跑一次任务四看屏幕上锁存的 split !! */
#define TASK4_ACCEL_RPM_PER_S       40.0f

/* 减速斜坡(rpm/s)。硬刹车会把球猛地甩向前方，减速和加速一样必须走斜坡。

   120 -> 40：120rpm/s 折合 42cm/s²，而杆能给球的加速度上限只有约 27cm/s²
   (见 ball.h)——前馈要求 120x7=840us，输出限幅只有 560us，【必然饱和】。
   也就是说这一段"走了斜坡"只是速度没突变，球该被甩还是被甩，前馈根本补
   不上。取 40 与加速端一致(14cm/s²、前馈 280us)，两端都在权限之内。

   顺带说明为什么这一段也值得管：评分的 split 在过 B 那一刻就锁存了，
   减速发生在之后，严格说不影响 ≤8s 那一条；但"行驶中球稳在中心"评委多半
   要看到车停稳为止，而且 42cm/s² 足以把球直接甩出管子。任务五那边同理
   (见 TASK56_DECEL_RPM_PER_S 的注释)。 */
#define TASK4_DECEL_RPM_PER_S       40.0f

/* 差速上限(rpm)。原先任务四没设，等于用 tracking.h 的全局默认 100 ——
   而 Track_Init() 每次启动都会把它复位回 100，所以不在这里显式设一次就
   永远是 100。

   差速越大两轮转速差越悬殊，车体的横摆角加速度越大，球被甩得越狠 ——
   这和任务五收紧到 50 是同一个理由(见 TASK56_STEER_LIMIT_RPM)。AB 段全是
   直线，转向本来就软(Kp=1.0)，正常跑根本顶不到 50；它防的是【偶发】的
   大偏差修正 —— 压到线边缘或短暂丢线时，100 的权限会让车猛地一拧，
   那一下横摆足以把球甩出 1cm。
   90±50 意味着轮速在 40~140 之间，直线修正绰绰有余。 */
#define TASK4_STEER_LIMIT_RPM       50.0f

/* 时间兜底(ms)。正常由里程触发停车，所以这个值必须留够余量 ——
   它一旦抢先触发走的是硬刹车(没有减速斜坡)，球会被直接甩出去，
   属于异常兜底而不是正常路径。

   12000 -> 14000：起步斜坡放缓到 40rpm/s(A->B 约 6.4s)、减速放缓到 40rpm/s
   (过 B 后 0.8s 匀速 + 2.5s 刹停)之后，一趟完整走完约 9.7s，12s 只剩 2.3s
   余量。兜底本来就该"永远不触发"，宁可给宽。 */
#define TASK4_RUN_TIME_MS           14000

/* ---------------- 任务四专用的转向参数 ----------------
   AB 段全是直线，不需要任务二那份过弯的修正力度。而直线上每一次左右修正
   都是一个横向加速度，直接作用在摆杆上 —— 残余画蛇就是晃球的主因。
   所以这里把 Kp 砍到一半、Kd 相对加大：转向更软、阻尼更足，车走得更"呆"，
   但球稳。代价是过弯能力下降，反正 AB 段用不上。 */
#define TASK4_STEER_KP              1.0f
#define TASK4_STEER_KI              0.0f
/* Kd 要跟着 Kp 一起缩，不能只砍 Kp。
   微分放大的是偏差的变化率，而直线上偏差本身很小，变化的主要成分是灰度质心
   的量化噪声 —— D/P 比例一高，噪声就被放大成方向上的细碎抖动(轻微摆头)。
   这里取 0.15，D/P = 0.15，和任务二的 0.125 基本一致。 */
#define TASK4_STEER_KD              0.15f

/* 直线任务把弯道减速关掉(设 0)，换取绝对匀速。
   速度只要在变，就是纵向加速度，球会前后窜 */
#define TASK4_CURVE_SLOWDOWN        0.0f

/* ================= 任务五 / 任务六 共用参数 ================= */

/**
  * 任务五：钢球置于摆杆中心 O，顺时针跑完整圈并通过 A，总时间 ≤30s，
  *         全程球须稳定在【中心】附近，误差 ≤1cm。
  * 任务六：同上，但球置于摆杆上的【任意指定位置】，须稳定在该位置附近。
  *
  * 两者对小车的要求一模一样 —— 同一圈、同样 30s、同样要求平顺。差别只在
  * 小球闭环的目标值(中心 vs 指定点)，与车怎么开无关，所以共用这一套参数。
  *
  * 和任务二跑的是同一圈，但目标恰好相反：任务二求快、求停得准，
  * 任务五/六求平顺。30s 的预算相当宽松(任务二 150rpm 只要 20s)，
  * 富余出来的时间全部用来降低加速度。
  */

/* 基准速度。6.14m / 0.281m/s ≈ 22s，加上斜坡约 23s，离 30s 还有 7s 余量。
   留这么多余量是因为实测速度通常比理论值偏低(任务四已经验证过)。
   弯道里球受到的横向加速度是 v²/R，与速度【平方】成正比 ——
   降速是压制弯道晃球最有效的手段，但也不能慢到吃光时间预算。 */
#define TASK56_BASE_RPM              80.0f

/* 加减速斜坡(rpm/s)。比任务四的 120 更缓：时间预算宽裕，
   没必要为了抢那零点几秒去加大冲击。

   60 -> 30：60rpm/s 折合车的加速度 60/60 x 21.05cm(轮周长) = 21cm/s²，要靠
   杆顶住它需要约 435us 的常驻倾角(换算见 ball.h 的 BALL_FF_US_PER_RPMS)，
   占掉 560us 输出权限的 78% —— 速度环积分顶摩擦要的那 150~250us 就没地方
   放了，前馈一饱和球照样被甩走。实测起步峰值 2.1cm，指标只给 1cm。
   30rpm/s 是 10.5cm/s²，前馈约 218us，权限还剩六成给反馈用。

   时间代价：0->80rpm 从 1.33s 变成 2.67s，整圈约多花 0.7s(23s -> 24s 上下)，
   离 30s 的上限还有大把余量 —— 这个任务本来就是拿时间换平顺。 */
#define TASK56_ACCEL_RPM_PER_S       30.0f
#define TASK56_DECEL_RPM_PER_S       30.0f

/* 转向参数。整圈有弯道，不能像任务四那样软到 1.0；
   但 80rpm 的弯比任务二 150rpm 轻松得多，1.5 够用。
   D/P 维持在 0.13 左右，避免噪声被微分放大成抖动 */
#define TASK56_STEER_KP              1.5f
#define TASK56_STEER_KI              0.0f
#define TASK56_STEER_KD              0.20f

/* 弯道减速关掉，换取全程匀速。
   速度只要在变就是纵向加速度。整圈有好几个弯，每个弯进出各一次加减速，
   累积下来对球的干扰比弯道本身的横向力还麻烦 */
#define TASK56_CURVE_SLOWDOWN        0.0f

/* 差速上限收紧到 50rpm(全局默认 100)。
   差速越大两轮转速差越悬殊，车体的横摆角加速度越大，球被甩得越狠。
   80±50 意味着轮速在 30~130 之间，过弯够用又不至于猛拽 */
#define TASK56_STEER_LIMIT_RPM       50.0f

/* 终点判定沿用任务二那套：进终点窗口(TASK_FINISH_WINDOW_M)才开始看横线、
   窗口内放宽判据，里程兜底防漏检 */
#define TASK56_DIST_STOP_M           (TASK_LAP_LENGTH_M + 0.15f)

/**
  * 通过 A 之后【继续匀速跑】这么久才开始减速。
  *
  * 意义在于把减速动作挪出评分时刻：车通过 A 的前后都保持匀速，
  * 纵向加速度为 0，球不会在评委看它的那一秒被拽走。
  * 减速推迟到 2 秒之后，那时车已经远离 A 点了。
  *
  * 这段滑行不计入评分时间 —— s_split_ms 在通过 A 的瞬间就锁存了。
  */
#define TASK56_COAST_MS              2000

/* 时间兜底(ms)。预计 23s 跑完，留到 35s。
   它一旦触发说明这一趟已经超时失败了，纯粹是防止车一直跑下去 */
#define TASK56_RUN_TIME_MS           35000

/* ================= 任务七参数(隐藏) ================= */

/**
  * 任务七：倒车 —— 不是赛题里的任务，是个把车往后挪一段的工具。
  *
  * 触发方式(两条，效果完全一样)：
  *   -长按 KEY1 约 0.8s：直接切到任务七【并立即启动】，不用再按 KEY2。
  *    短按 KEY1 仍然是在任务一~六之间循环，切不到这里来 —— 这就是"隐藏"
  *    的意思：不占用正常切换的循环，误触不到。
  *   -vofa 发 N7 切过来、再发 G 启动(或者按 KEY2)。
  *
  *   运行中长按无效(与短按切任务同一条规则)；要中途叫停按 KEY2 / 发 S。
  *
  * ---------------- 为什么倒车必须关掉循迹 ----------------
  * 灰度阵列装在车头。车往后开时，这排探头就变成了【拖在后面】的探头，
  * 循迹环的符号关系整个反过来 —— 按原来的方向修正等于正反馈，车会越修
  * 越歪，几拍之内就甩出赛道(推购物车倒着走的那种失稳)。
  *
  * 所以任务七【完全不跑循迹外环】，由任务层直接下达左右轮转速，两轮给同一个
  * 目标值，走直靠的是两路速度环各自把自己那个轮子按在同一个转速上
  * (见 task.c 的 Task_GetDriveTargets 和 app.c 里对它的调用)。
  *
  * 顺带的好处：不依赖灰度传感器，I2C 挂了照样能把车倒出来。
  *
  * 直线度取决于两轮的一致性，倒个半米量级没问题，不要指望它倒完整圈。
  */

/* 倒车速度(rpm)。取和任务五/六同一档的慢速：倒车看不见前方(其实是后方)，
   慢一点好收手；载着球的话这个速度也不至于把球甩掉。
   实际下发的是它的【负值】，见 task.c 的 Task7_Run() */
#define TASK7_BASE_RPM              80.0f

/* 倒车距离(m)，从启动算起的总行程(含最后减速滑行的那一段)。
   0.5m 够把车从终点线上挪开、重新摆位，又不至于一路倒进弯道里 */
#define TASK7_DIST_M                0.50f

/**
  * 减速提前量(m) —— 还剩这么远就开始收油门。
  *
  * 从 TASK7_BASE_RPM 按下面的斜坡降到 0 这段时间里车还会继续往后走，
  * 这个值就是那段距离，所以真正开始减速的位置是 TASK7_DIST_M 减去它。
  *
  * 估算：80rpm x 67mm 轮径 = 0.281m/s，60rpm/s 的斜坡加上 TASK_ACCEL_RISE_S
  * 的加速度建立时间约 1.6s，平均速度取一半 -> 0.22m。
  * 实测倒过头了就【加大】它(提前减速)，倒不够就减小。
  */
#define TASK7_BRAKE_M               0.22f

/* 加减速斜坡(rpm/s)。比任务五/六的 30 陡一些 —— 倒车不是评分项目，不必为了
   护住球把起步拖成 3 秒；但也没必要更陡，斜坡本身就是防止起步一顿把球甩掉。
   两个方向【必须给同一个值】：Task_RampBase() 是按"目标比当前大还是小"来
   选用哪一个的，倒车全程是负速度，加速那一段反而走的是 DECEL 那一路 */
#define TASK7_ACCEL_RPM_PER_S       60.0f
#define TASK7_DECEL_RPM_PER_S       60.0f

/* 【不设时间兜底】(与任务一同理)。别的任务都有一个 TASKxx_RUN_TIME_MS，
   那是为了防止评分任务超时了还在赛道上一路跑下去；倒车是个随手用的工具，
   不占评分时间，跑多久都无所谓，所以宁可让它一直倒下去也不要一个会
   【硬刹】的兜底 —— 兜底触发时走的是 Task_Finish() 里的刹车，杆上有球
   就是那一下把球甩掉。

   代价是里程判据成了唯一的结束条件：万一轮子打滑/编码器不动，车会一直
   往后倒到按 KEY2(或 vofa 发 S)为止。正常约 3.5s 倒完(1.5s 起步斜坡 +
   匀速 + 1.6s 减速)，超过这个数还没停就该伸手了。 */

/* ================= 类型 ================= */

typedef enum
{
  TASK_1 = 0,
  TASK_2,
  TASK_3,
  TASK_4,
  TASK_5,
  TASK_6,
  TASK_7,                 /* 隐藏：倒车。短按 KEY1 的循环切换会跳过它 */
  TASK_NUM
} Task_ID;

typedef enum
{
  TASK_STATE_IDLE = 0,    /* 待命，等 KEY2 */
  TASK_STATE_RUN,         /* 运行中 */
  TASK_STATE_DONE         /* 已完成，计时定格 */
} Task_State;

/* ================= 接口 ================= */

/* 初始化。须在 Track_Init() / Encoder_Init() 之后调用 */
void Task_Init(void);

/* 跑一拍任务调度。须每 TRACK_PERIOD_MS 调用一次(与循迹外环同拍) */
void Task_Update(void);

Task_ID    Task_GetId(void);
Task_State Task_GetState(void);
uint8_t    Task_IsRunning(void);

/**
  * @brief  直接指定任务号，语义等价于按 KEY1 循环切换到该任务
  * @note   仅在未运行(IDLE/DONE)时生效，运行中调用会被忽略 —— 与物理按键
  *         "运行中屏蔽切换"的保护规则一致，避免跑着跑着被远程指令误切。
  *         越界的 id 同样被忽略。供 vofa.c 的 N 指令使用
  */
void Task_SetId(Task_ID id);

/* 启动当前任务，等价于在空闲/已完成状态下按一次 KEY2。运行中调用是空操作。
   供 vofa.c 的 G 指令使用 */
void Task_Go(void);

/* 中途停止当前任务，等价于运行中按一次 KEY2(计时定格、车刹停)。未运行时
   调用是空操作。供 vofa.c 的 S 指令使用 */
void Task_Stop(void);

/**
  * @brief  当前任务是否需要小车行驶
  * @retval 0 表示这是个静止任务(如任务三：车不动、只有摆杆工作)
  * @note   app.c 据此决定要不要跑循迹外环。少了这道判断，静止任务一启动
  *         车就会自己沿线开走。
  */
uint8_t Task_UsesVehicle(void);

/**
  * @brief  取任务层【直接下达】的左右轮目标转速(rpm，负值为倒退)
  * @retval 1 = 本任务自己开车，两个出参已填好，app.c 应【跳过循迹外环】
  *             直接把它们当作速度环的目标；0 = 不接管，两个出参不动
  * @note   目前只有任务七(倒车)会返回 1。倒车时车头的灰度阵列变成拖在后面
  *         的探头，循迹环在这种几何下是正反馈，必须整个让位 —— 详见 task.h
  *         任务七参数区的说明。
  *
  *         与 Task_UsesVehicle() 的分工：那个回答"要不要动轮子"，这个回答
  *         "轮速由谁给"。倒车任务两者都成立(要动轮子、但轮速不由循迹给)。
  */
uint8_t Task_GetDriveTargets(float *left_rpm, float *right_rpm);

/* 行驶总时间(ms)。运行中实时累加，完成或停止后定格 */
uint32_t Task_GetElapsedMs(void);

/**
  * @brief  到达评分点时锁存的用时(ms)
  * @retval 0 表示还没到评分点
  * @note   任务四 = 通过 B 的时刻(≤8s)；任务五/六 = 通过 A 的时刻(≤30s)。
  *         评分看的是这个数，行驶总时间还包含之后的减速段，不能拿来对照。
  */
uint32_t Task_GetSplitMs(void);

/* 本次任务已行驶的距离(m) */
float Task_GetDistanceM(void);

#endif /* __TASK_H */
