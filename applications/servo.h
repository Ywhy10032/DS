#ifndef __SERVO_H
#define __SERVO_H

#include "main.h"

/**
  ******************************************************************************
  * 180 度舵机 (TIM4_CH4 / PD15)
  *
  * 机构：小球放在一根管子上，管子一端是固定活页(转轴)，另一端由舵机抬起/放下。
  *       舵机角度 -> 管子倾角 -> 小球沿管子滚动的加速度。
  *
  * CubeMX 已把 TIM4 配好：PSC=83 -> 84MHz/84 = 1MHz 计数(1 个计数正好 1us)，
  * ARR=19999 -> 20ms 周期 = 50Hz，正是舵机要的信号。所以脉宽可以直接按微秒写。
  ******************************************************************************
  */

/* ---------------- 舵机自身的电气规格 ----------------
   0.5ms~2.5ms 是 180 度舵机的常见规格，但各家有差异：有的是 1.0~2.0ms 对应
   180 度，有的 0.5~2.5ms 只转 120 度。这两个值只用于角度<->脉宽的换算，
   不参与保护。 */
#define SERVO_MIN_PULSE_US      500     /* 对应 0 度 */
#define SERVO_MAX_PULSE_US      2500    /* 对应 SERVO_MAX_ANGLE_DEG */
#define SERVO_MAX_ANGLE_DEG     180.0f

/**
  * ---------------- 机构安全行程（唯一的保护手段）----------------
  *
  * !! 必须按实测填写，这两个数是整个保护机制的全部 !!
  *
  * 舵机没有任何反馈回单片机：程序既读不到它转到了哪里，也读不到堵转电流。
  * 所以无法"检测到顶死再退回来"—— 唯一可行的保护就是【绝不发出越界的指令】。
  * 一旦指令超出机构能走的范围，舵机会持续堵转，电流拉满、几分钟就能烧掉，
  * 或者把连杆、活页掰断。
  *
  * 取值方法见本文件末尾的标定步骤。要点是：先找到机构的物理死点，
  * 然后【往里收 5~10 度的余量】再填进来，不要贴着死点填。
  * 余量是留给机构装配误差、齿轮间隙、以及舵机自身定位误差的。
  *
  * 所有设定接口(SetAngle / SetPulseUs / StepUs)都会被夹在这个范围内，
  * 没有任何绕过的路径。
  */
#define SERVO_SAFE_MIN_US       1050
#define SERVO_SAFE_MAX_US       2400

/**
  * 管子水平时的脉宽 —— 机构的工作原点，上电就回到这里。
  *
  * 注意它【不是】安全行程的中点(1050 与 2400 的中点是 1725)：机构是一端活页
  * 一端舵机抬升，连杆几何决定了水平点偏向行程的一侧。所以回原点必须用这个
  * 实测值，不能拿 (MIN+MAX)/2 去算。
  *
  * ---------------- 怎么测出来的 ----------------
  * 关键在于【有静摩擦时，一整段脉宽范围内球都不动】，所以"随便找个球不动的
  * 脉宽"是错的 —— 那只是落在静止带里的某一点，可能贴着边。正确做法是量出
  * 这条带子的两个边界，取中点：
  *
  *   球放管子中间静止 -> 往上加到球刚开始滚 = H(实测 1800)
  *   球复位再往下减到球刚开始滚 = L(实测 1480)
  *
  *   水平点   = (H+L)/2 = 1640
  *   静摩擦   = (H-L)/2 = 160  -> ball.h 的 BALL_STICTION_US
  *
  * ---------------- 1640 -> 1727：改用闭环反推，弃用手动扫描 ----------------
  *
  * 手动扫描有个躲不掉的坑：主界面 US 字段是轮流刷新的(约 280ms 一轮)，按住
  * 连发时读数滞后几十 us。这个滞后【只要在一个方向上更严重，中点就被拽偏】。
  * 上一版量到 L=1480 就是晚了近 180us，把中点从 1727 拽到了 1640。
  * (H=1800 只晚了一点，所以单看它反而接近真实带上沿 1785)
  *
  * 改用【闭环里反推】，没有人为判读环节：跑纯 PD(Kp=25)，把球从两侧拨开松手，
  * 记下它停住的位置。球静止时 D 项为 0，此时舵机倾角就是 Kp x 偏差，
  * 而它恰好是"推不动球的最大倾角"。设 c 为水平点修正量、T 为起步门槛：
  *
  *   球停在 10.5 不动     ->  |50  - c| <= T      (Kp x 2.0 = 50us)
  *   球停在 7.5  不动     ->  |125 - c| <= T      (Kp x 5.0 = 125us)
  *   球在 -125us 时动了   ->  |-125 - c| >  T
  *
  * 联立解出 c ~= 87us、T ~= 45us。同样 125us 的倾角【一个方向推得动、另一个
  * 推不动】，这种不对称只可能来自水平点偏移 —— 这是整个方法的判据来源。
  *
  * ---------------- 1727 -> 1757：同一方法迭代第二轮 ----------------
  * 改到 1727 后两侧都能动了(之前 7.5 那侧纹丝不动)，但仍不对称：
  *     从 17.5 回来停在 14.2  ->  静止倾角 25 x (-1.7) = -42.5us
  *     从 7.5  回来停在 8.4   ->  静止倾角 25 x (+4.1) = +102.5us
  * 两个倾角都推不动球，所以静止带至少覆盖 [-42.5, +102.5]，其中心落在 +30us
  * 而不是 0 —— 水平点还差 30us，故 1727 + 30 = 1757。
  * 同时得到门槛的新下界：带宽 >= 145us，即 T >= 72us(比第一轮估的 45 大，
  * 那轮只有两个样本且其中一个是靠动量冲进来的)。
  *
  * 迭代判据就是【两侧静止倾角是否对称】，比单点扫描稳健得多：动量、摩擦
  * 随位置的差异都只影响幅度，不影响"哪边更难推"这个符号。
  *
  * ---------------- 第三轮试到 1780，退回 1757 ----------------
  * 1780 实测【退步】：A 侧从"能回到 13.2"变成从 17.5 纹丝不动，-x 方向的
  * 推力被削掉了，说明补过头。只加 23us 就发生质变，恰恰说明早已在噪声里
  * 打转 —— 残余偏差远小于起步门槛，停止点本身就有 +-T 的自由度。
  * 最终取三轮里对称性最好的 1757(两侧差 0.7 / 2.5)。
  * 以下为当时的推算过程，留作记录：
  *     从 17.5 回来停在 13.2  ->  静止倾角 25 x (-0.7) = -17.5us
  *     从 7.5  回来停在 10.0  ->  静止倾角 25 x (+2.5) = +62.5us
  * 带中心 +22.5us，故 1757 + 23 = 1780。
  *
  * !! 迭代到此结束，不要再往下抠 !!
  * 上一轮补了 30us，带中心只从 +30 挪到 +22.5 —— 补偿没有全额兑现，说明剩下
  * 的不对称有相当一部分【不是水平点造成的】：
  *   - 动量差：两侧回中的行程不等(4.3cm vs 2.5cm)，走得远的一侧冲得更深，
  *             停止点天然偏向中心
  *   - 管子不均匀：两个停止点位于管子不同位置，局部斜率与摩擦本就有差异
  * 这两项都不是一个全局常数修得掉的。而且残余偏差(约 22us)已经小于起步门槛
  * T(>=72us)，球停在静止带里的哪一点本身就有 +-T 的自由度 —— 继续用停止点
  * 反推水平点，测量精度已经不如这个自由度大，属于拿噪声当信号。
  * 剩下的 2~3cm 是静摩擦造成的，交给 ball.h 的静摩擦补偿(阶段二)，
  * 那套机制本来就不要求水平点绝对精确。
  *
  * 由此得到两侧的可用行程：向下 1780-1050 = 730us，向上 2400-1780 = 620us。
  * 可用的对称量取小的那边，即 ±620us。
  *
  * !! 车身姿态一变就要重测 !! 起步门槛只有约 45us，而姿态每偏 1 度水平点就
  * 挪 80~160us —— 换个地面、换块垫子都足以让球停不住。
  */
#define SERVO_LEVEL_US          1757

/* ================= 基本接口 ================= */

/* 启动 PWM 输出。须在 MX_TIM4_Init() 之后调用 */
void Servo_Init(void);

/* 按角度设定，自动夹在 SERVO_SAFE_* 范围内 */
void Servo_SetAngle(float deg);
float Servo_GetAngle(void);

/* 直接按脉宽设定，同样受 SERVO_SAFE_* 约束 */
void Servo_SetPulseUs(uint16_t us);
uint16_t Servo_GetPulseUs(void);

/**
  * @brief  上一次设定是否被安全限位截断了
  * @note   给后面的小球闭环用：PID 算出的角度一旦超出机构行程，实际执行的是
  *         被夹住的值。此时若继续累积积分就会饱和，等球回来时要很久才退出来
  *         (表现为长时间失控)。所以外环看到本函数返回 1 时应该停止积分。
  */
uint8_t Servo_IsAtLimit(void);

/**
  * 微调步进(微秒)。TIM4 是 1MHz 计数，1us 就是硬件能给出的最小步进，
  * 换算成角度约 0.09 度。
  *
  * 注意舵机本身有【死区】：模拟舵机通常 5~10us、数字舵机 2~4us 以内的变化
  * 根本不响应。如果按键调了好几下都纹丝不动，把这个值加到 5 或 10，
  * 不是代码的问题。
  */
#define SERVO_STEP_US           1

/* 在当前脉宽上增减，正负均可，内部自动限幅 */
void Servo_StepUs(int16_t delta_us);

/* ================= 自检演示 ================= */

/**
  * 在标定出的安全行程内往复摆动：
  *   停在 MIN 1s -> 匀速升到 MAX -> 停 1s -> 匀速降回 MIN -> 周而复始
  *
  * 直接以【微秒】为单位扫，而不是换算成角度再扫：角度换算的基准是舵机的
  * 电气量程(500~2500)，跟机构行程无关，用角度扫会有一大半时间被限位夹住、
  * 卡在两端不动。
  *
  * 回程也走匀速而不是直接跳回去：舵机瞬间走满行程会把小球甩飞，
  * 对活页和连杆的冲击也很大。
  */
#define SERVO_DEMO_HOLD_MS      1000
#define SERVO_DEMO_SPEED_UPS    600.0f  /* 微秒/秒，1350us 的行程扫完约 2.3s */

void Servo_DemoInit(void);
void Servo_DemoUpdate(void);            /* 周期调用，内部按 tick 计时 */

#endif /* __SERVO_H */
