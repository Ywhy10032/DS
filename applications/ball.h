#ifndef __BALL_H
#define __BALL_H

#include "main.h"

/**
  ******************************************************************************
  * 球杆闭环 —— 串级(cascade)：位置环 -> 速度环 -> 舵机倾角
  ******************************************************************************
  *
  * ---------------- 为什么要串级 ----------------
  *
  * 被控对象是【双积分器】：倾角决定加速度，不是位置。
  *     倾角 --积分--> 速度 --积分--> 位置
  *
  * 单环 PID 直接拿"位置误差"去算倾角，要一口气跨过两级积分，先天难调；
  * 更要命的是它【无法在零误差处输出非零倾角】—— 而摩擦、管子下垂造成的
  * 恒定阻力恰恰需要一个常驻倾角去顶住。上一版为此堆了一整套外挂补偿
  * (摩擦前馈 + 静摩擦补偿状态机 + 下垂前馈 + 三档增益调度 + 瞄准偏置)，
  * 二十多个互相牵制的常量，本质上都是在【手工模拟一件事】：
  *
  *     "自动累积出维持运动所需要的那份恒定倾角"
  *
  * 而这正是速度环里【积分项】的天职。串级之后这些补偿全部删除。
  *
  * 拆成两级之后，每一级各自面对一个【单积分器】，都是好调的一阶对象：
  *     速度环(内)  倾角 -> 加速度 -> 速度       PI 就够，I 自动吃掉摩擦/下垂
  *     位置环(外)  速度指令 -> 位置             P 为主，输出是"要多快"
  *
  * ---------------- 数据流 ----------------
  *
  *   目标位置 ─┐
  *             ├─> 位置环 PID ─> 速度指令(cm/s，限幅) ─┐
  *   实测位置 ─┘                                       ├─> 速度环 PID ─> 倾角(us)
  *                                     实测速度 ──────┘
  *
  * 两级都在【收到新视觉帧】时各跑一拍(60fps)。串级要求内环比外环快，这里
  * 靠【增益差】拉开带宽而不是靠采样率差 —— 位置环的输出限幅(vel_limit_cms)
  * 同时也是"外环不许要求内环做到多快"的闸门。
  ******************************************************************************
  */

/* 目标位置(cm)。摆杆中心 O 实测在 12.5cm 处 */
#define BALL_TARGET_CM          12.5f

/**
  ******************************************************************************
  * ---------------- 整定步骤：务必按这个顺序 ----------------
  *
  * 【第 0 步：确认符号】
  *   BALL_VEL_KP 给一个很小的值(比如 5)，其余增益全 0。用手把球推一下：
  *     - 舵机往【阻碍球运动】的方向倾  -> 符号对
  *     - 舵机顺着球运动的方向倾        -> BALL_OUTPUT_SIGN 改成 -1
  *   符号错了是正反馈，球会瞬间冲到杆的一端，别在高增益下试。
  *
  * 【第 1 步：只调速度环，位置环全部置 0】
  *   把 BALL_POS_KP/KI/KD 全设为 0 —— 此时速度指令恒为 0，速度环的唯一
  *   任务就是"把球的速度拉到 0"。判据非常直观：
  *
  *       !! 用手把球推向任意方向，松手后球应该【立刻停住】，
  *          而且停在哪儿就待在哪儿，不自己往回走 !!
  *
  *   a) 先加 BALL_VEL_KP：球从"推了一直滑"变成"推一下很快被刹住"。
  *      加到球停得够干脆为止；加过头会看到球停下瞬间【抖一下】。
  *   b) 再加 BALL_VEL_KI：解决"球停下后慢慢自己溜走"(管子下垂/水平点残差
  *      造成的恒定阻力)。加到球松手后能【原地不动】为止。
  *      Ki 是这一版能删掉一整套补偿的关键，别跳过。
  *   c) BALL_VEL_KD 最后再考虑，多数情况保持 0 —— 见它自己的注释。
  *
  * 【第 2 步：再调位置环】
  *   速度环合格(推哪停哪)之后才动这里。
  *   a) 加 BALL_POS_KP：球开始自己往目标跑。小了慢吞吞，大了在目标附近
  *      来回摆 —— 加到【刚开始出现轻微来回】为止。
  *   b) 加 BALL_POS_KD 压住上面那个来回，直到基本不过冲。
  *   c) 最后加一点点 BALL_POS_KI，把"总差最后几毫米"消掉。
  *      两个环的 Ki 都应该很小，位置环的尤其。
  *
  * ---------------- 和常见说法的一处出入 ----------------
  * 网上讲这套方法时常说"速度环先加 P，推小球让它来回摆动(超调)"。在这套
  * 对象上【看不到那个现象】：速度指令为 0 时，纯 P 的速度环就是一个纯阻尼
  * 器(输出 = -Kp x 速度)，只会让球平滑减速，不可能来回摆。要等加了 Ki
  * 之后(PI 控一阶对象构成二阶系统)才可能出现振荡。所以第 1 步的判据要看
  * 【停得干不干脆 + 停住后走不走】，不是看有没有来回摆。
  ******************************************************************************
  */

/* ================= 速度环(内环)：速度误差(cm/s) -> 舵机倾角(us) ================= */

/**
  * 对象是"倾角 -> 加速度 -> 速度"，一个单积分器，【无延迟时】纯 P 就稳定。
  *
  * 量纲上 Kp 是 us 每 (cm/s)。取值先看【要多大倾角才推得动球】：实测静摩擦
  * 起步门槛约 110~150us，所以速度差 5cm/s 时如果只给出 50us，球根本不动。
  *
  * 30 -> 18：实测第一版(30/150)手推球后出现左右左右来回好几次才停 ——
  * 典型欠阻尼振铃。按无延迟的教科书公式 zeta=Kp/(2*sqrt(Ki)) 算，30/150
  * 应该是过阻尼(zeta≈1.22)，会振铃说明这个理论值被【视觉链路的延迟】吃掉了，
  * 和这一整晚反复撞见的"延迟偷走相位裕度"是同一件事。先退一档再重新爬。
  */
#define BALL_VEL_KP             18.0f

/**
  * !! 这一项是整个重构的核心，别设成 0 !!
  *
  * 速度环的积分负责【自动累积出维持当前速度所需要的那份恒定倾角】。
  * 上一版单环结构里，这件事是靠一大堆手工常量硬凑的：
  *     摩擦前馈(BALL_FRICTION_FF_US)   —— 猜一个常量去抵消库仑摩擦
  *     静摩擦补偿(一整套爬升状态机)     —— 球卡住时慢慢加倾角直到挣脱
  *     下垂前馈(BALL_SAG_US_PER_CM)     —— 按位置线性补管子的坡度
  *     瞄准偏置(TASK3_MINUS_AIM_OFFSET) —— 补稳态残差
  * 这些【全部】可以由这一个积分项自动完成，而且不需要事先测量摩擦门槛、
  * 不需要标定下垂斜率、换个场地也不用重标 —— 这才是串级真正的收益，
  * 也是上一版"鲁棒性差"的根本解法。
  *
  * 量纲 us 每 (cm/s · s)。
  *
  * 150 -> 40：积分是纯滞后项，叠加视觉链路本身的延迟最容易吃掉相位裕度，
  * 是这次实测振铃(左右来回好几次才停)最可疑的一项，所以比 Kp 砍得更狠——
  * 大约 1/4。40 意味着 2cm/s 的持续误差每秒累积 80us，爬到 150us 的量级
  * 需要约 2 秒，比原来慢，但这一步先求【不振荡】，速度是下一步的事。
  */
#define BALL_VEL_KI             55.0f

/** 
  * 速度环的 D 作用在【速度的微分】上，也就是加速度。而加速度是视觉位置
  * 【二次差分】的产物，噪声被放大两次，实测几乎不可用。
  *
  * 默认 0。只有当速度环 P/I 调好后仍观察到"球停下瞬间明显抖一下"、
  * 且确认不是 Kp 过大造成的，才小心地从 2 开始加。
  */
#define BALL_VEL_KD             0.0f

/**
  * 速度环积分限幅(us)。必须【大于】维持运动所需的最大恒定倾角，否则积分
  * 顶满了还是推不动球，会退回上一版"卡住不动"的老毛病。
  *
  * 需要覆盖的量：静摩擦起步门槛(实测 110~150us) + 管子下垂在 ±5cm 处造成的
  * 坡度(约 60us) + 水平点标定残差(几十 us) ≈ 250us 量级。取 350 留余量。
  *
  * 给大【几乎没有代价】：积分按误差累积，误差一消失它就回落；
  * 给小了却会直接导致推不动 —— 这条不对称和上一版补偿天花板是同一个道理。
  */
#define BALL_VEL_I_LIMIT_US     350.0f

/* ================= 位置环(外环)：位置误差(cm) -> 速度指令(cm/s) ================= */

/**
  * 量纲 (cm/s) 每 cm，也就是 1/秒 —— 物理含义是【偏差收敛的速率】。
  * 2.5 表示偏差 4cm 时要求以 10cm/s 靠近，大致 1/2.5 = 0.4 秒的时间常数。
  *
  * 太小球慢吞吞；太大会在目标附近来回摆(外环要求的速度内环跟不上)。
  * 按整定步骤第 2 步 a)，加到刚出现轻微来回为止，再用 Kd 压回去。
  */
/* !! 临时置 0，用于隔离测试速度环 !! 见下面 BALL_POS_KI/KD 同一处说明 */
#define BALL_POS_KP             0.0f

/**
  * 位置环积分：消掉"总差最后几毫米"。
  *
  * 要很小 —— 恒定阻力已经由【速度环】的积分吃掉了，这里只负责收拾外环
  * 自己的稳态残差。给大了会让球冲过目标再慢慢荡回来。
  * 整定时最后再加，从 0.2 起步。
  */
#define BALL_POS_KI             0.0f    /* 临时置 0，隔离测试用 */

/**
  * 位置环微分，压制 Kp 带来的过冲。作用在【测量位置】的微分上，
  * 也就是球的实际速度 —— 信号质量比速度环的 D(加速度)好得多，敢用。
  *
  * 量纲 (cm/s) 每 (cm/s)，无量纲。0.6 表示球以 1cm/s 靠近时，
  * 速度指令被压低 0.6cm/s。
  */
#define BALL_POS_KD             0.0f    /* 临时置 0，隔离测试用 */

/* 位置环积分限幅(cm/s)，即积分项最多能贡献多大的速度指令。
   位置环的积分本来就该很弱，1.5cm/s 足够收拾残差又不会喧宾夺主 */
#define BALL_POS_I_LIMIT_CMS    1.5f

/**
  * 速度指令限幅(cm/s) —— 外环能要求的最大速度。
  *
  * 它同时是串级的【带宽闸门】：串级要求内环明显快于外环，限住外环能提的
  * 要求，就等于保证内环跟得上。太大会让球冲过目标(内环来不及刹)，
  * 太小则整体变慢。
  *
  * 任务三要在 5 秒内走完 5+10=15cm，平均 3cm/s，加上起停的加减速，
  * 峰值需要 10cm/s 上下。12 留一点余量。
  */
#define BALL_VEL_LIMIT_CMS      12.0f

/* ================= 输出与机构 ================= */

/**
  * 舵机输出限幅(us)，相对水平点的最大偏移。
  * 机构对称可用行程约 ±590us(见 servo.h)，400 留足余量，
  * 同时避免深度饱和 —— 饱和期间积分仍在累积(虽有限幅)，退饱和会变慢。
  */
#define BALL_OUTPUT_LIMIT_US    400.0f

/**
  * !! 上电第一次务必确认这个符号 !!
  *
  * +1 表示"要让球往 x 增大的方向加速时，舵机脉宽应该增大"。
  * 取决于摄像头朝向和连杆抬升方向，任一装反都要改成 -1。
  * 验证方法见上面整定步骤的第 0 步。符号错了是正反馈。
  */
#define BALL_OUTPUT_SIGN        (+1.0f)

/* ================= 速度估计 ================= */

/**
  * 速度低通系数。速度是位置差分来的，差分把位置噪声放大了 1/dt 倍
  * (60fps 下约 60 倍)，不滤没法喂给速度环。
  *
  * 视觉端(ball_position.py 的 AdaptiveAlphaBetaFilter)已经对位置做过
  * 自适应平滑，所以这里的输入比"原始像素坐标"干净得多。
  *
  * !! 不用视觉发来的 vx_pixel_s !!
  * 那个值由 alpha-beta 滤波器的 beta 支路给出，而 beta 在球接近静止时
  * 会降到 0.01 —— 时间常数 dt/beta ≈ 16.7ms/0.01 ≈ 1.7 秒，慢得完全没法
  * 用于速度环。本地差分配这里的低通只有约 40ms 滞后，好得多。
  *
  * 系数越大响应越快、噪声越大。振荡时先怀疑 Kp，其次才是这里。
  */
#define BALL_VEL_LPF            0.30f

/* ================= 视觉数据的可用性 ================= */

/* 置信度低于此值的帧直接丢弃，不参与控制 */
#define BALL_MIN_CONFIDENCE     0.50f

/* 超过这么久没有可用帧就把杆放平并清空两级积分 */
#define BALL_TIMEOUT_MS         200

/* 帧间隔的合理范围(秒)。视觉端卡顿或刚上电时 dt 会异常，
   不夹住的话微分项会算出天文数字，舵机瞬间打死。
   下限按 60fps(16.7ms)留了余量 */
#define BALL_DT_MIN_S           0.005f
#define BALL_DT_MAX_S           0.150f

/* ================= 小车运动的前馈(任务四/五/六用) ================= */

/**
  * 加速度前馈。小车起步加速时，球因为惯性会相对摆杆向后滑。反馈控制对此
  * 无能为力 —— 它只能在球【已经被拽出去】之后才开始修正。
  *
  * 但小车的加速度是我们自己下达的指令，完全已知，可以在球动之前就把杆倾好。
  * 这一项【不是】串级要替代的对象：它补偿的是外部扰动，不是系统内部的
  * 恒定阻力，速度环的积分只能事后跟随，不能提前预判。
  *
  * 增益单位 us 每 (rpm/秒)，实测标定：跑任务四看起步瞬间球的最大位移，
  * 还往后滑就加大，反而往前冲就减小。
  */
#define BALL_FF_ENABLE          1
#define BALL_FF_US_PER_RPMS     2.0f

/**
  * 过弯前馈。实测关闭：它只补偿【稳态】向心加速度，而出入弯真正伤球的是
  * 角速度的【变化率】，那一段前馈非但帮不上忙还会自己造出一个扰动。
  */
#define BALL_FF_CURVE_ENABLE    0
#define BALL_FF_CURVE_GAIN      0.04f

/* ================= 按任务切换的参数组 ================= */

/**
  * 上面的 #define 是【默认值】。各任务对球杆的要求不同(任务三要在偏离中心
  * 5cm 的点上快速停稳；任务四/五/六要在小车行驶中把球稳在中心)，
  * 任务层在 Task_Start() 里按任务号装载对应的一组。
  *
  * 串级之后需要按任务区分的量只剩这几个 —— 上一版是二十多个。
  */
typedef struct
{
  float pos_kp, pos_ki, pos_kd;     /* 外环：位置误差 -> 速度指令 */
  float pos_i_limit_cms;
  float vel_limit_cms;              /* 速度指令限幅，兼作串级带宽闸门 */

  float vel_kp, vel_ki, vel_kd;     /* 内环：速度误差 -> 舵机倾角 */
  float vel_i_limit_us;

  float out_limit_us;               /* 舵机输出限幅 */
} Ball_Tune;

#define BALL_TUNE_DEFAULT_INIT                                  \
{                                                               \
  BALL_POS_KP, BALL_POS_KI, BALL_POS_KD,                        \
  BALL_POS_I_LIMIT_CMS, BALL_VEL_LIMIT_CMS,                     \
  BALL_VEL_KP, BALL_VEL_KI, BALL_VEL_KD,                        \
  BALL_VEL_I_LIMIT_US,                                          \
  BALL_OUTPUT_LIMIT_US                                          \
}

/* 装载一组参数，立即生效 */
void Ball_SetTune(const Ball_Tune *tune);

/* 回到宏定义的默认值 */
void Ball_ResetTune(void);

/* 读取当前生效的参数组 —— 外部只想改其中一两个增益(如 vofa.c 的在线调参)时，
   先取这份基准值再改动个别字段，不必知道其余字段该填什么 */
Ball_Tune Ball_GetTune(void);

/* ================= 接口 ================= */

/* 初始化，须在 Servo_Init() / Vision_Init() 之后调用 */
void Ball_Init(void);

/* 主循环周期调用。内部只在【收到新帧】时才跑一拍控制 */
void Ball_Update(void);

/* 使能/停用。停用时舵机回到水平点并清空两级积分 */
void Ball_Enable(uint8_t on);
uint8_t Ball_IsEnabled(void);

/* 改目标位置 */
void Ball_SetTarget(float cm);
float Ball_GetTarget(void);

/* 告知球杆控制器小车【当前的加速度】(rpm/秒)，正值为加速。匀速段传 0 */
void Ball_SetAccelFF(float rpm_per_s);
void Ball_SetCurveFF(float v_times_diff);

/* ---------------- 诊断 ---------------- */
float   Ball_GetPosCm(void);        /* 最近一次采纳的球位置 */
float   Ball_GetVelCmS(void);       /* 估算的球速度 */
float   Ball_GetVelSetCmS(void);    /* 位置环下达的速度指令 —— 串级调试的关键中间量 */
float   Ball_GetOutputUs(void);     /* 速度环输出，相对水平点的 us 偏移 */
uint8_t Ball_IsTracking(void);      /* 视觉可用且正在闭环 */

#endif /* __BALL_H */
