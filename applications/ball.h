#ifndef __BALL_H
#define __BALL_H

#include "main.h"

/**
  ******************************************************************************
  * 球杆闭环 —— 视觉测位置，舵机调倾角，把钢球稳在摆杆上的指定点
  *
  * ★ 控制律待重写 ★
  * 本文件只保留【框架与安全相关】的参数，控制律本体（增益调度 / 静摩擦补偿 /
  * 摩擦前馈 等）已全部移除。旧实现见 git 提交 42467a3。
  *
  * 重写前请先读 ball_notes.md —— 那里是实测得来、推导不出来的信息：
  * 起步门槛、视觉延迟给带宽划的硬上限、各个机制踩过的坑、整定顺序。
  *
  * 对象是【二阶不稳定】的：倾角决定的是球的加速度而不是位置，
  *     x'' = (5/7) * g * sin(theta)
  * 即一个零阻尼的双积分器。所以纯 P 必然等幅振荡，D 项是稳定的必要条件。
  ******************************************************************************
  */

/* ================= 目标 ================= */

/* 目标位置(cm)。摆杆中心 O 实测在 12.5cm 处 */
#define BALL_TARGET_CM          12.5f

/* ================= 控制参数（待整定） =================
   输出单位是"相对 SERVO_LEVEL_US 的舵机脉宽偏移(us)"。

   全部置 0 是【安全的初始状态】：输出恒为 0，杆保持水平，舵机不动。
   整定顺序见 ball_notes.md 第五节，要点是先加 Kd 再谈 Kp。
   历史参考值（最后一版稳定配置）：Kp=25、Ki=0、Kd=45。 */
#define BALL_KP                 0.0f    /* us 每 cm 偏差 */
#define BALL_KI                 0.0f    /* 双积分器对象相位裕度紧，能不用就不用 */
#define BALL_KD                 0.0f    /* us 每 (cm/s) 速度 */

/**
  * 输出限幅(us)：相对 SERVO_LEVEL_US 的最大偏移。
  *
  * 机构对称可用行程是 ±620us（1757-1050=707，2400-1757=643，取小），
  * 但【限幅不是越大越好】：限幅高会让饱和更深，而饱和本身就是失稳源 ——
  * 饱和期间 Kp/Kd 的比例关系完全失效，控制器退化成 bang-bang。
  * 反过来也不能压太低：限幅同时管着"加速"和"刹车"两个方向，
  * 压低了刹车权限也一起被砍，反而更容易冲过头。
  *
  * 300 是上一版失稳后退回来的值（曾提到 500，撞限幅振荡）。
  * 无论取多少，最终下发都还会被 Servo_SetPulseUs() 夹在 SERVO_SAFE_* 内。
  */
#define BALL_OUTPUT_LIMIT_US    300.0f

/* 积分限幅(us)。积分只该负责吃掉水平点几十 us 的残余标定误差，
   不要拿它去顶静摩擦 —— 那会引发粘滑振荡，详见 ball_notes.md */
#define BALL_INTEGRAL_LIMIT_US  40.0f

/**
  * !! 上电第一次务必确认这个符号 !!
  *
  * +1 表示"球偏向 x 增大的方向时，舵机脉宽应该增大"。这取决于摄像头的安装
  * 朝向和连杆的抬升方向，两者任一装反都要改成 -1。
  *
  * 符号错了就是正反馈，球会瞬间冲到杆的一端。
  * 验证方法：Kp/Ki/Kd 全为 0 时杆恒定水平，是安全的；只把 Kp 设成 2，
  * 用手把球放在 >12.5cm 的一侧，看杆倾斜的方向是否让球滚回中心。
  */
#define BALL_OUTPUT_SIGN        (+1.0f)

/* ================= 信号处理 ================= */

/**
  * 速度低通系数。速度是位置差分来的，噪声被 1/dt 放大了约 30 倍，不滤没法用。
  * 系数越小滤得越狠但滞后越大 —— 微分项对滞后极敏感，别低于 0.2。
  *
  * 实测参考：位置噪声约 0.1cm，差分后速度噪声约 1.3cm/s；取 0.30 时本级
  * 滞后约 75ms，视觉端另有延迟，合计 75~100ms —— 这条延迟就是闭环带宽的
  * 硬上限，越过之后加 Kd 不但无效反而更糟（见 ball_notes.md 第三节）。
  */
#define BALL_VEL_LPF            0.30f

/* ================= 前馈（车体运动补偿） ================= */

/**
  * 加速度前馈：小车起步加速时，球因惯性相对摆杆向后滑。反馈对此无能为力
  * （只能在球已被拽出去之后才修），但小车的加速度是我们自己下达的指令、
  * 完全已知，所以可以提前把杆倾到抵消惯性的角度。
  *
  * 增益单位是 us 每 (rpm/秒)，取决于连杆传动比，量不出来，靠实测标定：
  * 跑任务四看起步瞬间球的最大位移 —— 还往后滑就加大，反而往前冲就减小。
  *
  * 这一路【实测有效】，保持开启。
  */
#define BALL_FF_ENABLE          1
#define BALL_FF_US_PER_RPMS     2.0f

/**
  * 过弯前馈。入参是 v_avg x (右轮 - 左轮)，两个因子都用 rpm。
  *
  * !! 实测关闭 !! 开启后过弯反而变差：它只补偿了【稳态】向心加速度 v x omega，
  * 而出入弯真正伤球的是 omega 的【变化率】—— 出弯时轮速差骤降、前馈随之撤销，
  * 球被留在偏离位置上还带着速度。实测纯反馈已经能应付过弯。
  */
#define BALL_FF_CURVE_ENABLE    0
#define BALL_FF_CURVE_GAIN      0.04f   /* us 每 rpm^2 */

/* ================= 视觉帧的取用条件 ================= */

/* 置信度低于此值的帧直接丢弃，不参与控制 */
#define BALL_MIN_CONFIDENCE     0.50f

/* 超过这么久没有可用帧就把杆放平并清空控制器历史。
   视觉断链【必须】回平，不能保持上一次的输出 —— 斜着的杆会让球一直加速，
   几百毫秒就冲出去了；放平至少让它匀速滑行 */
#define BALL_TIMEOUT_MS         200

/* 帧间隔的合理范围(秒)。视觉端卡顿或刚上电时 dt 会异常，
   不夹住的话微分项会算出天文数字，舵机瞬间打死 */
#define BALL_DT_MIN_S           0.010f
#define BALL_DT_MAX_S           0.150f

/* ================= 接口 ================= */

/* 初始化，须在 Servo_Init() / Vision_Init() 之后调用 */
void Ball_Init(void);

/* 主循环周期调用。内部只在【收到新帧】时才跑一拍控制 */
void Ball_Update(void);

/* 使能/停用。停用时舵机回到水平点 */
void Ball_Enable(uint8_t on);
uint8_t Ball_IsEnabled(void);

/* 改目标位置，用于任务六的"任意指定位置" */
void Ball_SetTarget(float cm);
float Ball_GetTarget(void);

/**
  * @brief  告知球杆控制器小车【当前的加速度】(rpm/秒)，正值为加速
  * @note   由任务层在速度斜坡里调用。匀速段传 0。
  */
void Ball_SetAccelFF(float rpm_per_s);

/**
  * @brief  告知球杆控制器过弯量，入参为 v_avg x (右轮 - 左轮)，单位 rpm
  */
void Ball_SetCurveFF(float v_times_diff);

/* 诊断用 */
float   Ball_GetPosCm(void);        /* 最近一次采纳的球位置 */
float   Ball_GetVelCmS(void);       /* 估算的球速度 */
float   Ball_GetOutputUs(void);     /* 相对水平点的输出偏移 */
uint8_t Ball_IsTracking(void);      /* 视觉可用且正在闭环 */

#endif /* __BALL_H */
