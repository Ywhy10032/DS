#ifndef __BALL_H
#define __BALL_H

#include "main.h"

/**
  ******************************************************************************
  * 球杆闭环 —— 视觉测位置，舵机调倾角，把钢球稳在摆杆上的指定点
  *
  * 被控对象是【二阶不稳定】的：倾角决定的是球的加速度而不是位置，
  *     x'' = (5/7) * g * sin(theta)
  * 也就是一个双积分器。这带来两个必须记住的结论：
  *
  *   1. 纯 P 控制一定等幅振荡。双积分器本身没有任何阻尼，比例项只能提供
  *      "回中的力"，提供不了"刹车的力"，球会一次次冲过中点。
  *      D 项不是可选项，是稳定性的必要条件。
  *
  *   2. 杆放平不等于球会停 —— 只是不再加速。要让运动的球停下来，
  *      必须先把杆往【反方向】倾斜给它减速，这正是 D 项在做的事。
  ******************************************************************************
  */

/* 目标位置(cm)。摆杆中心 O 实测在 12.5cm 处 */
#define BALL_TARGET_CM          12.5f

/* ---------------- 控制参数 ----------------
   输出单位是"相对水平点的舵机脉宽偏移(us)"。
   整定顺序见 ball.c 末尾，要点是先把 Kd 加够再谈 Kp。 */
/* Kp 要大到"小偏差也能推动球"。球有静摩擦死区：倾角小于某个值时球根本不动，
   此时偏差再小也修正不了。1.5cm 偏差配 Kp=10 只有 15us 的倾角，远低于死区，
   球就卡在那儿了 —— 这不是精度问题，是压根没推动。 */
/* Kp 不能大到让输出经常饱和。一旦贴住 ±BALL_OUTPUT_LIMIT_US，Kp/Kd 的比例
   关系就全部失效，控制器退化成 bang-bang：全程满舵加速，等该刹车时已经晚了，
   表现就是"冲向中心并大幅过冲"。
   20 意味着偏差 7.5cm 以内都在线性区，日常调节不会打满。 */
#define BALL_KP                 20.0f   /* us 每 cm 偏差 */

/* 积分项：唯一能把稳态误差真正消到 0 的手段。
   比例项只能把误差按比例缩小 —— 稳态误差 = 残余倾角/Kp，Kp 翻倍误差减半，
   但永远不为零。而积分会持续累加倾角直到球真的被推动为止，
   无论残余来自水平点偏移还是静摩擦，它都能吃掉。
   代价是静摩擦系统特有的【粘滑振荡】：积分憋到球突然挣脱、冲过头、再反向憋。
   如果出现一顿一顿的来回摆，就是 Ki 太大，减半。 */
/* Ki 的大小要按【积分项多久能爬到有用的幅度】来定，不能凭感觉给小值。
   积分项每秒增长 Ki x 误差：Ki=3、误差 1.5cm 时每秒才涨 4.5us，
   爬到 40us 的限幅要 9 秒 —— 等不到它起作用，看起来就像"球停住不动了"。
   Ki=25 时每秒涨 37us，一秒多就能顶到限幅，才是能用的时间尺度。 */
#define BALL_KI                 25.0f

/* Kd/Kp 的比值决定"提前多久开始刹车"：控制器在 Kd*v > Kp*e 时开始反向倾杆，
   也就是速度超过 (Kp/Kd)*偏差 就踩刹车。比值越大刹得越早、过冲越小。
   上一版 23/50=0.46 刹得太晚，冲过头 2cm；现在 30/20=1.5，提前三倍多。 */
#define BALL_KD                 30.0f   /* us 每 (cm/s) 速度 */

/* 输出限幅(us)。相对 SERVO_LEVEL_US 的最大偏移，机构对称可用行程是 ±450us。
   放到 350 而不是原来的 150 —— 限幅同时管着"加速"和"刹车"两个方向，
   压得太低的话刹车权限也一起被砍了，反而更容易冲过头。
   限幅【不参与】下面的增益调度，始终保持这么大，
   免得球高速冲进细调区时刹车权限突然缩水。 */
#define BALL_OUTPUT_LIMIT_US    350.0f

/**
  * ---------------- 增益调度：先冲后细调 ----------------
  *
  * 静摩擦门槛 380us 意味着：Kp=20 时要 19cm 的偏差才能靠比例项自己起步。
  * 实际偏差只有几厘米，所以每一段都得干等静摩擦补偿从 0 爬到 380us
  * (约 1 秒)，球才动。任务三来回三段，光等就十几秒。
  *
  * 解法是偏差大时换一套激进参数，让比例项【一上来就顶过起步门槛】：
  * Kp=80 时 5cm 偏差直接给出 400us，球立刻动，完全跳过等待。
  * 进入细调区后再切回温柔的参数，保证不冲过头。
  *
  * 粗调段 Ki 设为 0：积分只在目标附近有意义，冲刺途中累积起来只会加剧过冲。
  */
#define BALL_GAIN_SCHEDULE      1
#define BALL_COARSE_ERR_CM      1.5f    /* 偏差大于此值走粗调 */
#define BALL_COARSE_KP          80.0f
#define BALL_COARSE_KD          35.0f

/* 积分限幅 80us。40us 不够突破静摩擦：1.5cm 偏差时比例项只有 30us，
   加满积分也才 70us，仍然推不动球。放到 80us 后总量能到 110us，
   离 150us 的总限幅还有余地，不至于一有偏差就饱和。 */
#define BALL_INTEGRAL_LIMIT_US  80.0f

/**
  * !! 上电第一次务必确认这个符号 !!
  *
  * +1 表示"球偏向 x 增大的方向时，舵机脉宽应该增大"。这取决于摄像头的
  * 安装朝向和连杆的抬升方向，两者任一装反都要改成 -1。
  *
  * 符号错了就是正反馈：球会被越推越远，瞬间冲到杆的一端。
  * 安全的验证方法见 ball.c 末尾 —— 先别开闭环，用手把球放在偏离中心的位置，
  * 看程序算出的 OUT 方向对不对。
  */
#define BALL_OUTPUT_SIGN        (+1.0f)

/**
  * ---------------- 静摩擦补偿 ----------------
  *
  * 球从【静止】起步需要的倾角，远大于维持滚动需要的倾角。这正是
  * "用力拨开能归位、轻轻拨 2~3cm 却纹丝不动"的原因：
  *   - 用力拨：球全程带着速度，只需克服动摩擦，PID 的常规输出就够了
  *   - 轻轻拨：球静止，要重新起步得先突破静摩擦，而小偏差算出的小倾角
  *             够不着这个门槛，控制器输出不为零但球就是不动
  *
  * 靠加大 Kp/Ki 去硬凑是不对的 —— 那会让大偏差时严重过冲。正确做法是只在
  * "球几乎静止 且 仍有偏差"时，把输出幅度顶到足以起步的最小值。
  * 球一旦动起来(速度超过阈值)补偿立刻退出，交还给正常的 PID，
  * 所以不会在目标附近来回推。
  *
  * BALL_STICTION_US 怎么测：把 app.c 的 APP_SERVO_MODE 改成 APP_SERVO_MANUAL，
  * 球放在杆上静止，用 KEY3/KEY4 从水平点开始一点点加脉宽，球刚开始滚动时的
  * 偏移量就是它。填进来时略微加一点余量。
  */
#define BALL_STICTION_ENABLE    1

/* 起步所需的输出幅度上限，实测值。
   补偿量是从 0 【缓慢爬升】到这个值的，不是一步到位 —— 直接给 300us 会把球
   一脚踢飞，冲过头后停下、再踢回来，形成粘滑往复。缓慢爬升则会在"刚好够用"
   的倾角处让球起步，起步速度最小、过冲也最小。 */
#define BALL_STICTION_US        520.0f

/* 球相对"补偿开始时的位置"挪动超过这个距离，就判定为已经起步，立刻撤销补偿。
   用位置而不是速度做判据：位置噪声只有 0.1cm，而速度是差分出来的、噪声有
   3cm/s，还被低通滤了约 130ms —— 等速度反应过来时，球已经带着 380us 的
   大倾角猛加速了 130ms，必然冲过目标。位置判据没有这个延迟。 */
#define BALL_STICTION_MOVE_CM   0.3f

/* 补偿爬升速率(us/秒)。400 意味着最坏情况 0.75s 爬到 300us。
   太快等于阶跃(踢飞球)，太慢则响应迟钝 */
#define BALL_STICTION_RAMP_UPS  800.0f

/**
  * 偏差小于此值就不再启动补偿 —— 这是个【刻意设置的死区】，不是精度妥协。
  *
  * 起步门槛 380us 意味着球一动就是 0.5cm 起步距离加上惯性滑行，执行机构的
  * 分辨率就这么粗。拿这么粗的一脚去消除 1cm 的残差，必然冲过头，然后反向
  * 再来一脚 —— 结果就是在目标两侧永远摆荡。
  *
  * 而任务要求是【误差 ≤1cm】而不是 0。稳稳停在 0.8cm 是合格的，
  * 在 0 附近来回摆荡反而随时可能超出 1cm。所以死区取 0.8：
  * 落进来就收手，留 0.2cm 余量给视觉误差。
  *
  * 想要更小的稳态误差，出路是降低机械摩擦(让 BALL_STICTION_US 降下来)，
  * 而不是缩小这个死区 —— 死区一缩，摆荡立刻回来。
  */
#define BALL_STICTION_ERR_CM    0.8f

/* 速度高于此值才认为球真的动了。
   门槛必须高于速度估计的噪声底：位置有 0.1cm 抖动、30fps 差分出来就是 3cm/s，
   阈值给 1.0 的话噪声会不断把补偿误判成"球动了"并清零，
   补偿永远攒不到能起步的幅度，表现就是舵机上下摆而球纹丝不动 */
#define BALL_STICTION_VEL_CMS   4.0f

/* ---------------- 速度低通 ----------------
   速度是位置差分来的，噪声被 1/dt 放大了 30 倍。它同时喂给微分项(Kd=30 时
   3cm/s 的噪声就是 90us 的输出抖动)和静摩擦判据，不滤没法用。
   系数越小滤得越狠但滞后越大 —— 微分项对滞后很敏感，别低于 0.2 */
#define BALL_VEL_LPF            0.25f

/**
  * ---------------- 加速度前馈 ----------------
  *
  * 小车起步加速时，球因为惯性会相对摆杆向后滑。反馈控制对此无能为力 ——
  * 它只能在球【已经被拽出去】之后才开始修正，那几厘米是躲不掉的。
  *
  * 但小车的加速度是我们自己下达的指令，完全已知。既然知道，就可以在球动之前
  * 先把杆倾到能抵消这份惯性的角度 —— 这就是前馈。它不依赖测量，
  * 因此没有任何滞后，是解决"起步被拽走"的唯一正确手段。
  *
  * 增益单位是 us 每 (rpm/秒)。理论值取决于连杆的传动比，量不出来，
  * 用实测标定：跑任务四，看起步瞬间球的最大位移
  *     还是往后滑  -> 加大
  *     反而往前冲  -> 减小
  *     几乎不动    -> 对了
  */
#define BALL_FF_ENABLE          1
#define BALL_FF_US_PER_RPMS     2.0f

/**
  * 过弯前馈。稳态过弯的向心加速度 a = v x omega，而角速度 omega 正比于
  * 左右轮速差 —— 车速和轮速差都是我们自己下达的指令，所以同样完全已知，
  * 同样应该前馈而不是等球被甩出去再修。
  *
  * 入参是 v_avg x (右轮 - 左轮)，两个因子都用 rpm，
  * 轮径、轮距、重力加速度、连杆传动比这些常数全部并进本增益里。
  *
  * 标定：跑任务四/五，看过弯时球的位移
  *     还是被甩向同一侧  -> 加大
  *     反而甩向另一侧    -> 减小，或者【把符号取反】(几何朝向决定，算不出来)
  */
#define BALL_FF_CURVE_ENABLE    1
#define BALL_FF_CURVE_GAIN      0.04f   /* us 每 rpm^2 */

void Ball_SetCurveFF(float v_times_diff);

/**
  * @brief  告知球杆控制器小车【当前的加速度】(rpm/秒)，正值为加速
  * @note   由任务层在速度斜坡里调用。匀速段传 0。
  */
void Ball_SetAccelFF(float rpm_per_s);

/* 置信度低于此值的帧直接丢弃，不参与控制 */
#define BALL_MIN_CONFIDENCE     0.50f

/* 超过这么久没有可用帧就把杆放平并清空积分 */
#define BALL_TIMEOUT_MS         200

/* 帧间隔的合理范围(秒)。视觉端卡顿或刚上电时 dt 会异常，
   不夹住的话微分项会算出天文数字，舵机瞬间打死 */
#define BALL_DT_MIN_S           0.010f
#define BALL_DT_MAX_S           0.150f

/* ================= 接口 ================= */

/* 初始化，须在 Servo_Init() / Vision_Init() 之后调用 */
void Ball_Init(void);

/* 主循环周期调用。内部只在【收到新帧】时才跑一拍控制 */
void Ball_Update(void);

/* 使能/停用。停用时舵机回到水平点 */
void Ball_Enable(uint8_t on);
uint8_t Ball_IsEnabled(void);

/* 改目标位置，用于任务六的"任意指定位置" */
void Ball_SetTarget(float cm);
float Ball_GetTarget(void);

/* 诊断用 */
float   Ball_GetPosCm(void);        /* 最近一次采纳的球位置 */
float   Ball_GetVelCmS(void);       /* 估算的球速度 */
float   Ball_GetOutputUs(void);     /* 相对水平点的输出偏移 */
uint8_t Ball_IsTracking(void);      /* 视觉可用且正在闭环 */

#endif /* __BALL_H */
